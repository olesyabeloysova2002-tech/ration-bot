def get_ingredient_price(name, amount, unit):
    """Рассчитать стоимость ингредиента по прайсу. Если не нашли — вернём None."""
    if name not in INGREDIENT_PRICES:
        return None
    p = INGREDIENT_PRICES[name]
    if unit == "г":
        return round(p * amount / 1000, 1)
    if unit == "мл":
        return round(p * amount / 1000, 1)
    if unit == "шт":
        return round(p * amount, 1)
    return round(p * amount, 1)


